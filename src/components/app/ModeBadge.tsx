import { cn } from "@/components/ui/primitives";
import type { GenerationMode } from "@/lib/domain/replies";

export function ModeBadge({ mode }: { mode: GenerationMode }) {
  const demo = mode === "demo";
  return (
    <span
      title={demo ? "No AI provider is configured. Results are pre-written samples." : "Replies are generated by AI"}
      className={cn(
        "inline-flex items-center gap-1.5 rounded-full border px-2.5 py-1 text-[11px] font-medium",
        demo ? "border-warn/30 bg-warn/10 text-warn" : "border-accent/30 bg-accent-soft text-accent",
      )}
    >
      <span className={cn("size-1.5 rounded-full", demo ? "bg-warn" : "bg-accent")} />
      {demo ? "Demo mode" : "AI on"}
    </span>
  );
}
